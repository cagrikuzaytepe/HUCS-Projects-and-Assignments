"""
Hücre 6: AR (Artırılmış Gerçeklik) Yardımcı Fonksiyonu (Crop)
"""

def crop_center(img, target_aspect_ratio):
    """
    Görüntüyü hedef en-boy oranına göre merkezden kırpar.
    """
    h, w = img.shape[:2]
    img_aspect = w / h

    if img_aspect > target_aspect_ratio:
        # Görüntü hedeften daha geniş, genişliği kırp
        new_w = int(target_aspect_ratio * h)
        offset = (w - new_w) // 2
        cropped_img = img[:, offset:offset + new_w]
    elif img_aspect < target_aspect_ratio:
        # Görüntü hedeften daha yüksek, yüksekliği kırp
        new_h = int(w / target_aspect_ratio)
        offset = (h - new_h) // 2
        cropped_img = img[offset:offset + new_h, :]
    else:
        # En-boy oranları zaten aynı
        cropped_img = img

    return cropped_img

print("Hücre 6 (AR Crop Fonksiyonu) tanımlandı.")

