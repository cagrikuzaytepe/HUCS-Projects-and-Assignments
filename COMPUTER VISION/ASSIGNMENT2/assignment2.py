def compute_homography_ransac_upgraded(src_pts, dst_pts, iterations=1000, threshold=5.0):
    """
    RANSAC uygular (manuel implementasyon).
    YENİ: Inlier/Outlier görselleştirmesi için 'inlier_mask' ve
    rapor tablosu için 'reprojection_error' döndürür.
    """
    max_inliers = 0
    best_H = None
    best_inlier_mask = None # Indeksler yerine maske
    n_points = len(src_pts)

    if n_points < 4:
        return None, None, None

    # Tüm noktaları homojen koordinatlara çevir (döngü dışında bir kez)
    src_pts_hom = np.hstack((src_pts, np.ones((n_points, 1))))

    for _ in range(iterations):
        # 1. Rastgele 4 nokta seç
        indices = random.sample(range(n_points), 4)

        # 2. Bu 4 noktayı NORMALLEŞTİR
        src_sample, T_src = normalize_points(src_pts[indices])
        dst_sample, T_dst = normalize_points(dst_pts[indices])

        # 3. Normalleştirilmiş noktalara DLT uygula
        H_norm = compute_homography_dlt(src_sample, dst_sample)
        if H_norm is None: continue

        # 4. Homografiyi "geri normalleştir" (un-normalize)
        H_candidate = np.linalg.inv(T_dst) @ H_norm @ T_src
        if np.any(np.isnan(H_candidate)): continue

        # 5. Tüm noktaları kullanarak inlier'ları bul
        transformed_pts_hom = (H_candidate @ src_pts_hom.T).T

        # Sıfıra bölme hatalarını önle
        z = transformed_pts_hom[:, 2]
        z[np.abs(z) < 1e-8] = 1.0 # Geçersizleri 1 yap
        transformed_pts = transformed_pts_hom[:, :2] / z[:, np.newaxis]

        # Yeniden projeksiyon hatasını (reprojection error) TÜM noktalar için hesapla
        errors = np.linalg.norm(dst_pts - transformed_pts, axis=1)

        # YENİ: Indeksler yerine boolean maske kullan
        current_inlier_mask = (errors < threshold)
        current_inlier_count = np.sum(current_inlier_mask)

        # 6. En iyi modeli sakla
        if current_inlier_count > max_inliers:
            max_inliers = current_inlier_count
            best_inlier_mask = current_inlier_mask
            best_H = H_candidate # best_H'yi sakla, H_norm'u değil

    # 7. Tüm inlier'ları kullanarak homografiyi yeniden hesapla (daha stabil sonuç için)
    final_H = None
    mean_reprojection_error = None

    if best_inlier_mask is not None and max_inliers > 4:
        inlier_indices = np.where(best_inlier_mask)[0]

        # Yine normalizasyon kullanarak!

        # --- HATA BURADAYDI ---
        # ÖNCEKİ (HATALI):
        # src_inliers, T_src_final = normalize_points(src_pts[inlier_indices])
        # dst_inliers, T_dst_final = normalize_points(dst_pts[inlier_indices])

        # DÜZELTİLMİŞ (DOĞRU):
        src_inliers_norm, T_src_final = normalize_points(src_pts[inlier_indices])
        dst_inliers_norm, T_dst_final = normalize_points(dst_pts[inlier_indices])
        # ------------------------

        # H_norm_final = compute_homography_dlt(src_inliers_norm, dst_inliers_norm)
        # Yukarıdaki düzeltme ile bu satır artık doğru çalışacak:
        H_norm_final = compute_homography_dlt(src_inliers_norm, dst_inliers_norm)

        if H_norm_final is not None:
            final_H = np.linalg.inv(T_dst_final) @ H_norm_final @ T_src_final

            # YENİ: Sadece inlier'lar üzerindeki ortalama hatayı raporla
            inliers_hom = src_pts_hom[inlier_indices]
            transformed_inliers_hom = (final_H @ inliers_hom.T).T
            z_inliers = transformed_inliers_hom[:, 2]
            z_inliers[np.abs(z_inliers) < 1e-8] = 1.0
            transformed_inliers = transformed_inliers_hom[:, :2] / z_inliers[:, np.newaxis]

            inlier_errors = np.linalg.norm(dst_pts[inlier_indices] - transformed_inliers, axis=1)
            mean_reprojection_error = np.mean(inlier_errors)

    # best_inlier_mask, tüm 'good_matches' listesiyle aynı boyuttadır
    return final_H, best_inlier_mask, mean_reprojection_error

