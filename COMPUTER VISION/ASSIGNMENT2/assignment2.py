def create_panorama_with_intermediates(img1, img2, H):
    """
    İki görüntüyü birleştirir[cite: 57].
    YENİ: Rapor için ara görselleri döndürür.
    :return: (panorama, warped_img2, overlap_mask)
    """
    H = H.astype(np.float32)
    h1, w1 = img1.shape[:2]; h2, w2 = img2.shape[:2]

    # Tuvalin (canvas) boyutlarını hesapla
    corners2 = np.array([[0, 0], [0, h2], [w2, h2], [w2, 0]], dtype=np.float32).reshape(-1, 1, 2)
    transformed_corners = cv2.perspectiveTransform(corners2, H)
    corners1 = np.array([[0, 0], [0, h1], [w1, h1], [w1, 0]], dtype=np.float32).reshape(-1, 1, 2)
    all_corners = np.concatenate((corners1, transformed_corners), axis=0)

    x_min, y_min = np.int32(all_corners.min(axis=0).ravel())
    x_max, y_max = np.int32(all_corners.max(axis=0).ravel())

    # Görüntüleri pozitif koordinatlara kaydırmak için öteleme matrisi
    trans_dist = [-x_min, -y_min]
    H_trans = np.array([[1, 0, trans_dist[0]], [0, 1, trans_dist[1]], [0, 0, 1]], dtype=np.float32)

    width, height = x_max - x_min, y_max - y_min

    # 1. Çarpıtılmış görüntü (RAPORDA İSTENEN) [cite: 60, 134]
    warped_img2 = cv2.warpPerspective(img2, H_trans @ H, (width, height), borderValue=(0, 0, 0))

    # 2. Referans görüntüyü (img1) tuvale yerleştir
    panorama = np.zeros((height, width, 3), dtype=np.uint8)
    panorama[trans_dist[1]:h1+trans_dist[1], trans_dist[0]:w1+trans_dist[0]] = img1

    # 3. Birleştirme (Blending)
    mask_warped = np.any(warped_img2 > 0, axis=2)
    mask_pano = np.any(panorama > 0, axis=2)

    warped_only = mask_warped & ~mask_pano
    panorama[warped_only] = warped_img2[warped_only]

    # Çakışan alan (RAPORDA İSTENEN) [cite: 61, 134]
    overlap_mask = mask_warped & mask_pano

    # Basit ortalama (Simple averaging) veya doğrusal harmanlama (linear blending) [cite: 59]
    if np.any(overlap_mask):
        panorama[overlap_mask] = cv2.addWeighted(panorama[overlap_mask], 0.5, warped_img2[overlap_mask], 0.5, 0)

    # YENİ: Ara görselleri de döndür
    return panorama, warped_img2, overlap_mask

