def extract_features(image, method='sift'):
    """
    Verilen görüntüden anahtar noktaları ve tanımlayıcıları çıkarır.
    PDF [cite: 34] SIFT, SURF, ve ORB yöntemlerini ister.
    """
    if method.lower() == 'sift':
        detector = cv2.SIFT_create()
    elif method.lower() == 'surf':
        try:
            # Bu, opencv-contrib-python gerektirir
            detector = cv2.xfeatures2d.SURF_create()
        except AttributeError:
            print("SURF'u kullanmak için 'opencv-contrib-python' paketini kurun.")
            print("SIFT'a geri dönülüyor...")
            detector = cv2.SIFT_create()
    elif method.lower() == 'orb':
        detector = cv2.ORB_create(nfeatures=2000)
    else:
        raise ValueError("Desteklenmeyen metot. 'sift', 'surf' veya 'orb' kullanın.")

    keypoints, descriptors = detector.detectAndCompute(image, None)
    return keypoints, descriptors

def match_features(des1, des2, method='sift', ratio_thresh=0.75):
    """
    İki tanımlayıcı setini eşleştirir ve Lowe's ratio test uygular[cite: 39].
    """
    if method.lower() in ['sift', 'surf']:
        # SIFT/SURF için NORM_L2
        bf = cv2.BFMatcher(cv2.NORM_L2, crossCheck=False)
    else: # ORB için NORM_HAMMING
        bf = cv2.BFMatcher(cv2.NORM_HAMMING, crossCheck=False)

    # k=2, her bir tanımlayıcı için en iyi 2 eşleşmeyi bulur
    matches = bf.knnMatch(des1, des2, k=2)

    good_matches = []
    # 'matches' listesindeki her bir öğe (m, n) çifti içerir
    for m, n in matches:
        # m: en iyi eşleşme, n: ikinci en iyi eşleşme
        if m.distance < ratio_thresh * n.distance:
            good_matches.append(m)

    return good_matches

def normalize_points(points):
    """
    Noktaları DLT'nin sayısal kararlılığı için normalleştirir[cite: 51].
    """
    centroid = np.mean(points, axis=0)
    mean_dist = np.mean(np.linalg.norm(points - centroid, axis=1))

    if mean_dist < 1e-8:
        scale = 1.0
    else:
        scale = np.sqrt(2) / mean_dist

    T = np.array([
        [scale, 0, -scale * centroid[0]],
        [0, scale, -scale * centroid[1]],
        [0, 0, 1]
    ])

    points_hom = np.hstack((points, np.ones((points.shape[0], 1))))
    normalized_points_hom = (T @ points_hom.T).T

    normalized_points_hom_z = normalized_points_hom[:, 2]
    # Sıfıra bölmeyi önle
    normalized_points_hom_z[np.abs(normalized_points_hom_z) < 1e-8] = 1.0

    normalized_points = normalized_points_hom[:, :2] / normalized_points_hom_z[:, np.newaxis]

    return normalized_points, T

def compute_homography_dlt(src_pts, dst_pts):
    """
    4 veya daha fazla noktadan DLT kullanarak homografi hesaplar[cite: 46, 50].
    Bu, cv2.findHomography() KULLANILMAYAN manuel implementasyondur[cite: 48].
    """
    if src_pts.shape[0] < 4: return None

    A = []
    for i in range(src_pts.shape[0]):
        x, y = src_pts[i]; u, v = dst_pts[i]
        # DLT denklemleri
        A.extend([
            [-x, -y, -1, 0, 0, 0, u*x, u*y, u],
            [0, 0, 0, -x, -y, -1, v*x, v*y, v]
        ])

    A = np.asarray(A)
    # SVD çözümü
    _, _, Vh = np.linalg.svd(A)

    # Homografi vektörü h, Vh'nin son satırıdır
    last_element = Vh[-1, -1]
    if abs(last_element) < 1e-8: return None # Geçersiz çözüm

    h = Vh[-1, :] / last_element
    return h.reshape(3, 3)

