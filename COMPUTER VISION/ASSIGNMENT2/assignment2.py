# LÜTFEN VERİ SETİ YOLUNU KONTROL EDİN
# Kaggle için: '/kaggle/input/assgnmentthesecond/ar_dataset'
# Yerel makine için: 'ar_data' (eğer kodla aynı dizindeyse)
ar_data_path = '/kaggle/input/pa2-data/ar_dataset'
book_video_path = os.path.join(ar_data_path, 'book.mov') # [cite: 76]
source_video_path = os.path.join(ar_data_path, 'ar_source.mov') # [cite: 78]
cover_image_path = os.path.join(ar_data_path, 'cv_cover.jpg') # [cite: 77]

# 1. Referans kapak görüntüsünü yükle ve özelliklerini çıkar (bu sadece bir kez yapılır)
cover_image = cv2.imread(cover_image_path)
if cover_image is None:
    print(f"HATA: Kapak görüntüsü '{cover_image_path}' yüklenemedi. AR kısmı çalıştırılamıyor.")
else:
    cover_gray = cv2.cvtColor(cover_image, cv2.COLOR_BGR2GRAY)
    kp_cover, des_cover = extract_features(cover_gray, 'sift') # SIFT genellikle en stabil olanıdır
    h_cover, w_cover = cover_image.shape[:2]
    # Kapağın en-boy oranı hesaplandı [cite: 90, 91]
    cover_aspect_ratio = w_cover / h_cover
    print(f"Referans kapak görüntüsü ({w_cover}x{h_cover}) yüklendi.")

    # 2. Video yakalama nesnelerini oluştur [cite: 82]
    cap_book = cv2.VideoCapture(book_video_path)
    cap_source = cv2.VideoCapture(source_video_path)

    if not cap_book.isOpened() or not cap_source.isOpened():
        print("HATA: Video dosyaları (book.mov veya ar_source.mov) yüklenemedi.")
    else:
        # 3. Çıktı videosu için VideoWriter'ı ayarla [cite: 89]
        frame_width = int(cap_book.get(cv2.CAP_PROP_FRAME_WIDTH))
        frame_height = int(cap_book.get(cv2.CAP_PROP_FRAME_HEIGHT))
        fps = int(cap_book.get(cv2.CAP_PROP_FPS))
        output_video_path = 'ar_dynamic_result.mp4' # [cite: 89, 98, 164]
        fourcc = cv2.VideoWriter_fourcc(*'mp4v')
        out = cv2.VideoWriter(output_video_path, fourcc, fps, (frame_width, frame_height))

        frame_count = 0

        # İpucu [cite: 102] - İşlemi hızlandırmak için kare atlama (örn: her 2 karede 1)
        # 1 = her kareyi işle, 2 = her 2 karede 1 işle
        frame_skip = 1

        print("AR video oluşturma işlemi başlıyor... Bu işlem biraz zaman alabilir[cite: 106].")

        last_good_frame = None # Titremeyi önlemek için

        while cap_book.isOpened():
            ret_book, frame_book = cap_book.read()
            if not ret_book:
                break # Kitap videosu bitti

            # Kaynak videoyu oku, biterse başa sar [cite: 86]
            ret_source, frame_source = cap_source.read()
            if not ret_source:
                cap_source.set(cv2.CAP_PROP_POS_FRAMES, 0)
                ret_source, frame_source = cap_source.read()

            frame_count += 1
            if frame_count % frame_skip != 0:
                # Atlanan kareler için son başarılı kareyi yaz (daha akıcı) [cite: 103]
                if last_good_frame is not None:
                    out.write(last_good_frame)
                else:
                    out.write(frame_book) # İlk karelerse orijinali yaz
                continue

            # 1. Kitap videosunun mevcut karesinden özellikleri çıkar [cite: 84]
            frame_book_gray = cv2.cvtColor(frame_book, cv2.COLOR_BGR2GRAY)
            kp_frame, des_frame = extract_features(frame_book_gray, 'sift')

            # 2. Kapak ile mevcut kare arasında özellikleri eşleştir [cite: 84]
            if des_frame is not None and len(des_frame) > 2:
                good_matches_ar = match_features(des_cover, des_frame, method='sift', ratio_thresh=0.75)
            else:
                good_matches_ar = []

            final_frame_to_write = frame_book.copy() # Başlangıçta orijinal kare

            # 3. Yeterli eşleşme varsa homografiyi hesapla [cite: 85]
            if len(good_matches_ar) > 10: # (min 4, ama 10 daha stabil)
                src_pts_ar = np.float32([kp_cover[m.queryIdx].pt for m in good_matches_ar]).reshape(-1, 2)
                dst_pts_ar = np.float32([kp_frame[m.trainIdx].pt for m in good_matches_ar]).reshape(-1, 2)

                # RANSAC ve Normalizasyonlu DLT'yi kullan [cite: 85]
                # (AR için daha hızlı RANSAC)
                H_ar, _, _ = compute_homography_ransac_upgraded(src_pts_ar, dst_pts_ar, iterations=500, threshold=5.0)

                if H_ar is not None:
                    # 4. Kaynak videonun karesini kitap kapağının üzerine çarpıt

                    # 'crop_center' kullanılıyor
                    frame_source_cropped = crop_center(frame_source, cover_aspect_ratio)

                    # Kırpılan görüntüyü kapağın tam boyutuna yeniden boyutlandır
                    frame_source_resized = cv2.resize(frame_source_cropped, (w_cover, h_cover))

                    # Kırpılmış ve yeniden boyutlandırılmış kareyi çarpıt [cite: 87]
                    warped_source = cv2.warpPerspective(frame_source_resized, H_ar, (frame_width, frame_height))

                    # 5. Bir maske oluşturarak sadece kitap kapağı alanını birleştir (Compositing) [cite: 88]
                    mask = np.zeros_like(frame_book, dtype=np.uint8)
                    cover_corners = np.array([[0, 0], [0, h_cover-1], [w_cover-1, h_cover-1], [w_cover-1, 0]], dtype=np.float32).reshape(-1, 1, 2)
                    transformed_corners = cv2.perspectiveTransform(cover_corners, H_ar)
                    cv2.fillPoly(mask, [np.int32(transformed_corners)], (255, 255, 255))

                    mask_inv = cv2.bitwise_not(mask)
                    book_masked = cv2.bitwise_and(final_frame_to_write, mask_inv)
                    # warped_source'u da maskeleyerek sadece ilgili alana eklenmesini garantile
                    warped_source_masked = cv2.bitwise_and(warped_source, mask)

                    final_frame_to_write = cv2.add(book_masked, warped_source_masked)
                    last_good_frame = final_frame_to_write # Son başarılı kareyi sakla

                else:
                    # Homografi bulunamazsa, son başarılı kareyi kullan
                    if last_good_frame is not None:
                        final_frame_to_write = last_good_frame

            else:
                # Eşleşme bulunamazsa, son başarılı kareyi kullan
                if last_good_frame is not None:
                    final_frame_to_write = last_good_frame

            # Çıktı karesini yaz [cite: 89]
            out.write(final_frame_to_write)

        # Her şeyi serbest bırak
        cap_book.release()
        cap_source.release()
        out.release()
        # cv2.destroyAllWindows() # Colab/Jupyter'da gereksiz

        print(f"AR videosu başarıyla '{output_video_path}' olarak kaydedildi.")